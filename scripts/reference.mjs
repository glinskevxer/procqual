// Writes the command reference out of the command tree itself.
//
// A reference kept by hand goes out of date with the first option somebody
// adds and nobody notices for a year. This walks the tree the program actually
// builds, so the only way for the reference to be wrong is for the tree to be
// wrong. CI runs it with --check and fails if the file on disk differs.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { buildProgram } from '../dist/cli/program.js';
import { RecordingOutput } from '../dist/cli/output.js';
import { memoryContext } from '../dist/cli/context.js';

const target = resolve('docs/cli.md');

function describeOption(option) {
  const flags = option.flags;
  const required = option.mandatory ? ' (required)' : '';
  const fallback =
    option.defaultValue === undefined || option.defaultValue === false
      ? ''
      : ` [default: ${String(option.defaultValue)}]`;
  return `- \`${flags}\`${required} — ${option.description}${fallback}`;
}

function describeCommand(command, path, lines) {
  const name = [...path, command.name()].join(' ');
  // A command that only groups others has nothing of its own to say, and its
  // description is already printed as the section heading above.
  const isGroup = command.commands.length > 0;
  if (path.length > 0 && !isGroup) {
    lines.push(`### ${name}`);
    lines.push('');
    if (command.description() !== '') {
      lines.push(command.description());
      lines.push('');
    }
    const usage = command.usage();
    lines.push('```');
    lines.push(`${name} ${usage}`.trimEnd());
    lines.push('```');
    lines.push('');
    const options = command.options.filter((option) => option.long !== '--help');
    if (options.length > 0) {
      for (const option of options) {
        lines.push(describeOption(option));
      }
      lines.push('');
    }
  }
  for (const child of command.commands) {
    if (child.name() === 'help') {
      continue;
    }
    describeCommand(child, [...path, command.name()], lines);
  }
}

function render() {
  const program = buildProgram(new RecordingOutput(), memoryContext());
  const lines = ['# arc command reference', ''];
  lines.push('Generated by `npm run reference`. Do not edit by hand.');
  lines.push('');
  for (const child of program.commands) {
    if (child.name() === 'help') {
      continue;
    }
    lines.push(`## ${child.name()}`);
    lines.push('');
    if (child.description() !== '') {
      lines.push(child.description());
      lines.push('');
    }
    describeCommand(child, ['arc'], lines);
  }
  return `${lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`;
}

const rendered = render();
const check = process.argv.includes('--check');

if (!check) {
  writeFileSync(target, rendered, 'utf8');
  process.stdout.write(`reference written to ${target}\n`);
} else {
  let onDisk = '';
  try {
    onDisk = readFileSync(target, 'utf8');
  } catch {
    onDisk = '';
  }
  if (onDisk !== rendered) {
    process.stderr.write('docs/cli.md is out of date, run npm run reference\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('reference is up to date\n');
  }
}
